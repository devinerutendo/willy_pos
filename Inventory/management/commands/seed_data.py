# ---------------------------------------------------------------------------
# Command
# ---------------------------------------------------------------------------

class Command(BaseCommand):
    help = "Seed the database with dummy categories, products, stock and suppliers"

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete existing seeded data and exit WITHOUT reseeding",
        )

    def handle(self, *args, **options):
        self.stdout.write(self.style.MIGRATE_HEADING("=== Database Seeder ==="))

        # ── 1. Resolve a system user (seed admin) ────────────────────────────
        admin = self._get_or_create_admin()

        # ── 2. Optionally clear old data then exit immediately ────────────────
        if options["clear"]:
            self._clear_data()
            self.stdout.write(self.style.SUCCESS(
                "✅  All seeded data has been cleared. No data was re-inserted."
            ))
            return

        # ── 3. Locations ─────────────────────────────────────────────────────
        locations = self._seed_locations(admin)

        # ── 4. Suppliers ─────────────────────────────────────────────────────
        self._seed_suppliers(admin)

        # ── 5. Categories + Products ─────────────────────────────────────────
        products_created = self._seed_categories_and_products(admin)

        # ── 6. Stock ─────────────────────────────────────────────────────────
        self._seed_stock(products_created, locations)

        self.stdout.write(self.style.SUCCESS("\n✅  Seeding complete!"))
        self.stdout.write(
            f"   Categories : {len(CATEGORIES_PRODUCTS)}\n"
            f"   Products   : {sum(len(v) for v in CATEGORIES_PRODUCTS.values())}\n"
            f"   Locations  : {len(locations)}\n"
            f"   Suppliers  : {len(SUPPLIERS)}\n"
        )

    # ── helpers ──────────────────────────────────────────────────────────────

    def _get_or_create_admin(self):
        """Return the first superuser, or create a seed admin if none exists."""
        admin = User.objects.filter(is_superuser=True).first()
        if admin:
            self.stdout.write(f"  Using existing admin: {admin.email}")
            return admin

        self.stdout.write(self.style.WARNING(
            "  No superuser found – creating seed admin (seed@admin.local / SeedPass123!)"
        ))
        admin = User.objects.create_superuser(
            username="seed_admin",
            email="seed@admin.local",
            password="SeedPass123!",
            first_name="Seed",
            last_name="Admin",
        )
        return admin

    def _clear_data(self):
        self.stdout.write(self.style.WARNING("  Clearing existing seed data..."))
        stock_count, _ = Stock.objects.all().delete()
        product_count, _ = Product.objects.all().delete()
        category_count, _ = Category.objects.all().delete()
        supplier_count, _ = Supplier.objects.all().delete()
        location_count, _ = Location.objects.filter(
            name__in=[loc["name"] for loc in LOCATIONS]
        ).delete()
        self.stdout.write(
            f"  Deleted → Stock: {stock_count} | Products: {product_count} | "
            f"Categories: {category_count} | Suppliers: {supplier_count} | "
            f"Locations: {location_count}\n"
        )

    def _seed_locations(self, admin):
        created = []
        for loc_data in LOCATIONS:
            loc, new = Location.objects.get_or_create(
                name=loc_data["name"],
                defaults={
                    "address": loc_data["address"],
                    "is_active": True,
                    "created_by": admin,
                    "updated_by": admin,
                },
            )
            created.append(loc)
            status = "created" if new else "exists"
            self.stdout.write(f"  Location [{status}]: {loc.name}")
        return created

    def _seed_suppliers(self, admin):
        for s_data in SUPPLIERS:
            supplier, new = Supplier.objects.get_or_create(
                name=s_data["name"],
                defaults={
                    **s_data,
                    "is_active": True,
                    "created_by": admin,
                    "updated_by": admin,
                },
            )
            status = "created" if new else "exists"
            self.stdout.write(f"  Supplier [{status}]: {supplier.name}")

    def _seed_categories_and_products(self, admin):
        all_products = []
        for cat_name, products in CATEGORIES_PRODUCTS.items():
            category, cat_new = Category.objects.get_or_create(
                name=cat_name,
                defaults={
                    "description": f"{cat_name} products",
                    "is_active": True,
                    "created_by": admin,
                    "updated_by": admin,
                },
            )
            cat_status = "created" if cat_new else "exists"
            self.stdout.write(
                self.style.SUCCESS(f"\n  Category [{cat_status}]: {category.name}")
            )

            # Tuples: (name, barcode, cost_price, selling_price)
            # SKU is auto-generated by the model on save — not supplied here.
            for (p_name, barcode, cost, sell) in products:
                product, p_new = Product.objects.get_or_create(
                    barcode=barcode,
                    defaults={
                        "name": p_name,
                        "category": category,
                        "cost_price": Decimal(str(cost)),
                        "selling_price": Decimal(str(sell)),
                        "reorder_level": random.randint(5, 20),
                        "is_active": True,
                        "created_by": admin,
                        "updated_by": admin,
                    },
                )
                all_products.append(product)
                p_status = "created" if p_new else "exists"
                self.stdout.write(f"    Product [{p_status}]: {product.name}  (SKU: {product.sku})")

        return all_products

    def _seed_stock(self, products, locations):
        """Give each product a random opening stock at each location."""
        self.stdout.write("\n  Seeding stock levels...")
        for product in products:
            for location in locations:
                qty = random.randint(20, 150)
                reserved = random.randint(0, min(5, qty))
                stock, new = Stock.objects.get_or_create(
                    product=product,
                    location=location,
                    defaults={
                        "quantity": qty,
                        "reserved_quantity": reserved,
                    },
                )
                if not new:
                    # Already seeded – skip to avoid overwriting live data
                    pass
        self.stdout.write("  Stock levels set.")